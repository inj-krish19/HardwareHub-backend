"""
Bring an existing database in line with the SQLAlchemy models.

Run with: python -m app.db.sync_schema
Print the same changes as plain SQL (for the Neon SQL editor or psql):
          python -m app.db.sync_schema --print-sql

What it does (additive only, never destructive):
  1. creates any table that is missing
  2. adds any column that exists in a model but not in the table
  3. creates any index declared on a model that is missing (for example the
     unique guide-slug index). If an index cannot be created because the
     existing data breaks it (say, duplicate titles), it prints a warning and
     carries on
  4. gives every guide without a slug one (see app/db/backfill_slugs.py)
  5. lists tables in the database that no model uses (it does NOT drop them)

Why this exists: Base.metadata.create_all() (used by init_db) only creates
missing TABLES. It never adds a column or index to a table that already
exists, so after a model changes you would otherwise write ALTER TABLE by
hand. Safe to run repeatedly; a second run changes nothing.
"""
import sys

from sqlalchemy import inspect, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session
from sqlalchemy.schema import CreateColumn, CreateIndex, CreateTable

import app.models  # noqa: F401  (registers every model on Base.metadata)
from app.db.backfill_slugs import assign_missing_slugs
from app.db.base import Base
from app.db.session import engine

# The same slug backfill as app/db/backfill_slugs.py, in plain SQL. It only
# touches guides whose slug is empty.
SLUG_BACKFILL_SQL = """\
WITH base AS (
    SELECT id,
           COALESCE(
               NULLIF(trim(both '-' from left(trim(both '-' from regexp_replace(lower(title), '[^a-z0-9]+', '-', 'g')), 80)), ''),
               'guide'
           ) AS b
    FROM symptom
    WHERE slug IS NULL
),
numbered AS (
    SELECT id, b, row_number() OVER (PARTITION BY b ORDER BY id) AS rn FROM base
)
UPDATE symptom s
SET slug = CASE WHEN n.rn = 1 THEN n.b ELSE n.b || '-' || n.rn END
FROM numbered n
WHERE s.id = n.id AND s.slug IS NULL;"""


def build_sql() -> str:
    """The additive changes as one idempotent SQL script (IF NOT EXISTS everywhere)."""
    dialect = postgresql.dialect()
    tables = Base.metadata.sorted_tables
    out = [
        "-- Generated by: python -m app.db.sync_schema --print-sql",
        "-- Safe to run more than once: every statement is IF NOT EXISTS or only fills empty values.",
        "",
        "-- 1. tables",
    ]
    out += [str(CreateTable(t, if_not_exists=True).compile(dialect=dialect)).strip() + ";" for t in tables]
    out += ["", "-- 2. columns added after a table was first created"]
    for table in tables:
        for column in table.columns:
            if column.primary_key:
                continue
            ddl = str(CreateColumn(column).compile(dialect=dialect)).strip()
            out.append(f'ALTER TABLE "{table.name}" ADD COLUMN IF NOT EXISTS {ddl};')
    out += ["", "-- 3. indexes"]
    for table in tables:
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            out.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
    out += ["", "-- 4. give every guide a URL slug", SLUG_BACKFILL_SQL, ""]
    return "\n".join(out)


def sync_schema() -> None:
    tables_before = set(inspect(engine).get_table_names())
    Base.metadata.create_all(bind=engine)  # step 1: missing tables
    inspector = inspect(engine)  # fresh inspector so it sees the new tables
    created = sorted(set(Base.metadata.tables) - tables_before)
    added: list[str] = []
    with engine.begin() as conn:
        for table in Base.metadata.sorted_tables:  # step 2: missing columns
            existing = {c["name"] for c in inspector.get_columns(table.name)}
            for column in table.columns:
                if column.name in existing:
                    continue
                ddl = CreateColumn(column).compile(dialect=engine.dialect)
                conn.execute(text(f'ALTER TABLE "{table.name}" ADD COLUMN {ddl}'))
                added.append(f"{table.name}.{column.name}")

    indexes_made: list[str] = []
    for table in Base.metadata.sorted_tables:  # step 3: missing indexes
        for index in table.indexes:
            try:
                with engine.begin() as conn:
                    if not engine.dialect.has_index(conn, table.name, index.name):
                        index.create(conn)
                        indexes_made.append(index.name)
            except SQLAlchemyError as exc:
                print(f"WARNING: could not create index {index.name}: {exc.orig if hasattr(exc, 'orig') else exc}")

    with Session(engine) as db:  # step 4: slugs for guides that have none
        slugs_set = assign_missing_slugs(db)

    model_tables = set(Base.metadata.tables)
    extra = sorted(set(inspector.get_table_names()) - model_tables)  # step 5: report only

    print(f"Created {len(created)} table(s): {', '.join(created) if created else 'none'}")
    print(f"Added {len(added)} column(s): {', '.join(added) if added else 'none, schema already up to date'}")
    print(f"Created {len(indexes_made)} index(es): {', '.join(indexes_made) if indexes_made else 'none'}")
    print(f"Assigned slugs to {slugs_set} guide(s)")
    if extra:
        print(f"Tables in the database that no model uses (left untouched): {', '.join(extra)}")


if __name__ == "__main__":
    if "--print-sql" in sys.argv:
        print(build_sql())
    else:
        sync_schema()